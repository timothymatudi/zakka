export const MESSAGES: Record<Locale, Dict> = { en, es, fr, pt, ar, zh, hi, sw, de, id };

export function t(locale: Locale | null | undefined, key: Key, vars: Record<string, string | number> = {}): string {
  const s = (MESSAGES[locale ?? 'en'] ?? en)[key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

export function countryName(code: string, locale: Locale): string {
  try {
    return new Intl.DisplayNames([locale], { type: 'region' }).of(code) ?? code;
  } catch {
    return code;
  }
}
